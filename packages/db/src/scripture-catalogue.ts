/*
 * The books, canons and translations Berean Study ships with. This is reference
 * data about Scripture and contains no Scripture text. It has no imports so the
 * browser can use it too.
 */

export const bookGroups = [
	"Law",
	"History",
	"Poetry & wisdom",
	"Major prophets",
	"Minor prophets",
	"Gospels",
	"Pauline epistles",
	"General epistles",
	"Apocalyptic",
	"Deuterocanonical",
] as const;

export type BookGroup = (typeof bookGroups)[number];

export type BookDefinition = {
	name: string;
	slug: string;
	shortName: string;
	testament: "old" | "new";
	group: BookGroup;
	fullTitle: string;
	/** KJV totals, used to measure progress. Absent for books outside the 66. */
	expectedChapters: number | null;
	expectedVerses: number | null;
	aliases: readonly string[];
};

function book(
	name: string,
	shortName: string,
	testament: "old" | "new",
	group: BookGroup,
	fullTitle: string,
	expectedChapters: number | null,
	expectedVerses: number | null,
	aliases: readonly string[],
): BookDefinition {
	return {
		name,
		slug: name.toLowerCase().replaceAll(" ", "-"),
		shortName,
		testament,
		group,
		fullTitle,
		expectedChapters,
		expectedVerses,
		aliases,
	};
}

